-- Supabase schema & strict Row Level Security (RLS) for Vision Surveillance event mirror.
-- Run this inside the Supabase SQL Editor once when enabling CLOUD_SYNC=true.

-- 1. Event metadata mirror table (never stores face embeddings, raw crops, or consent notes)
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_event_id BIGINT NOT NULL UNIQUE,
    camera_name TEXT NOT NULL,
    event_type TEXT NOT NULL,
    event_created_at TIMESTAMPTZ NOT NULL,
    event_created_ts DOUBLE PRECISION NOT NULL,
    zone_id TEXT NULL,
    zone_name TEXT NULL,
    person_label TEXT NULL,
    confidence DOUBLE PRECISION NULL,
    thumbnail_path TEXT NULL,
    synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_events_created_ts
    ON public.events (event_created_ts);

-- 2. Enable strict Row Level Security and block all anonymous/public client access
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.events FROM anon;
REVOKE ALL ON TABLE public.events FROM authenticated;

-- Service-role key (stored only in local .env as SUPABASE_KEY) bypasses RLS server-side,
-- or you can scope access to a dedicated backend role via auth.role() = 'service_role'.
DROP POLICY IF EXISTS "Deny public access to events" ON public.events;
CREATE POLICY "Deny public access to events"
    ON public.events
    AS RESTRICTIVE
    FOR ALL
    TO anon, authenticated
    USING (false)
    WITH CHECK (false);

-- 3. Private Storage bucket for small JPEG event thumbnails (max 320px wide)
INSERT INTO storage.buckets (id, name, public)
VALUES ('event-thumbnails', 'event-thumbnails', false)
ON CONFLICT (id) DO UPDATE SET public = false;

-- Block public/anon Storage object access via RLS
DROP POLICY IF EXISTS "Deny public thumbnail access" ON storage.objects;
CREATE POLICY "Deny public thumbnail access"
    ON storage.objects
    AS RESTRICTIVE
    FOR ALL
    TO anon, authenticated
    USING (bucket_id <> 'event-thumbnails')
    WITH CHECK (bucket_id <> 'event-thumbnails');
